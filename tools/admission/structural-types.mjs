import {R,tup,UV,lab} from './structural-syntax.mjs';
import {scalar,universe,bound,arrow,family,apply,typeValue,identity} from './structural-relations.mjs';

// Source metadata are read from the same checked Book. This structural reader
// does not instantiate templates, mutate the Book, search for inhabitants,
// classify by declaration spelling, or overwrite source bodies.
export class SourceTypes {
  constructor(B,book) { this.B=B;this.book=book;this.families=new Map();this.depth=1000000;this.symbol=0;this.boundTypes=new Map(); }
  q(q) {
    if(q.$==='None')return 0;
    if(q.$==='Lone')return 1;
    if(q.$==='Many')return 2;
    throw Error('A symbolic source quantity needs its complete finite layout translation: '+q.$);
  }
  name(k) { return this.kernelNames?.get(k)??this.B.name_key(k).replace(/[^A-Za-z0-9_.]|^[.0-9]/g,c=>'_'+c.codePointAt(0).toString(16)+'_'); }
  open(F,ctx,key) {
    const level=this.depth++,v=this.B.Var(F.k,level),next=new Map(ctx);next.set(level,key);
    this.boundTypes.set(key,F.A);
    return {v,ctx:next};
  }
  type(T,ctx=new Map()) {
    const A=this.B.term_wnf(this.book,T);
    if(A.$==='Qnt')return scalar({$:'Enu',ks:['Q0','Q1','Q2']},2);
    if(A.$==='Typ')return universe(A.g.$==='Qua'?this.q(A.g.q):this.value(A.g,this.B.Qnt(),ctx));
    if(A.$==='All') {
      const key='binder.'+this.symbol++,x=this.open(A,ctx,key);
      return arrow(this.q(A.q),key,this.type(A.A,ctx),this.type(A.B(x.v),x.ctx));
    }
    if(A.$==='ADT') {
      const d=this.book.tlds[A.k];
      if(d?.$!=='ADT')throw Error('Missing checked datatype '+A.k);
      // Constructor relations preserve defining equations under open inputs.
      this.descriptor(A.k);
      let U=d.T;const args=[];
      for(const x of A.x) {
        const F=this.B.term_wnf(this.book,U);if(F.$!=='All')throw Error('Malformed datatype telescope');
        args.push(this.value(x,F.A,ctx));U=F.B(x);
      }
      return family(A.k,args);
    }
    if(A.$==='Var') {
      const key=ctx.get(A.i);if(key===undefined)throw Error('Unbound source type level '+A.i);
      return bound(key);
    }
    if(A.$==='App')return apply(this.value(A.f,null,ctx),this.value(A.x,null,ctx));
    if(A.$==='Eql')return identity(this.type(A.T,ctx),this.value(A.a,A.T,ctx),this.value(A.b,A.T,ctx));
    throw Error('Structural source type not implemented: '+A.$);
  }
  value(x,T,ctx) {
    let annotation=this.B.term_force(x);while(annotation.$==='Ann'){T??=annotation.T;annotation=this.B.term_force(annotation.x);}
    const value=this.readValue(x,T,ctx);
    return {...value,sourceTerm:x,sourceType:T??value.sourceType};
  }
  readValue(x,T,ctx) {
    let a=this.B.term_force(x);
    while(a.$==='Ann'){T??=a.T;a=this.B.term_force(a.x);}
    if(a.$==='Var') {
      const key=ctx.get(a.i);if(key===undefined)throw Error('Unbound source value level '+a.i);
      return {...bound(key),sourceType:this.boundTypes.get(key)};
    }
    if(a.$==='App'){
      const f=this.value(a.f,null,ctx),F=f.sourceType===undefined?null:this.B.term_wnf(this.book,f.sourceType);
      return {...apply(f,this.value(a.x,F?.$==='All'?F.A:null,ctx)),sourceType:F?.$==='All'?F.B(a.x):undefined};
    }
    if(a.$==='Ref') {
      const key=ctx.get('ref:'+a.k);
      if(key!==undefined)return bound(key);
      if(this.book.tlds[a.k]?.$==='ADT')return typeValue(this.type(a,ctx));
      return {tag:'erased-reference',key:a.k,physicalViews:this.physicalViews,sourceType:this.book.tlds[a.k]?.T};
    }
    if(a.$==='Lit'&&a.k==='Nat') {
      this.descriptor('Nat');
      return {tag:'nat-literal',n:a.v,type:family('Nat')};
    }
    if(a.$==='Qua')return {tag:'constant',value:lab('Q'+this.q(a.q)),type:this.type(this.B.Qnt(),ctx)};
    if(a.$==='Min')return {tag:'quantity-minimum',a:this.value(a.a,this.B.Qnt(),ctx),b:this.value(a.b,this.B.Qnt(),ctx)};
    // A source type is a value of a universe. Its relation dictionary is
    // generated by the same structural type interpreter.
    if(['Typ','All','ADT','Qnt'].includes(a.$))return typeValue(this.type(a,ctx));
    return {tag:'source',term:x,expected:T,context:new Map(ctx)};
  }
  originalType(T,env,ctx){
    const B=this.B;
    if(T.tag==='family')return B.ADT(T.key,T.args.map(x=>this.originalValue(x,env,ctx)));
    if(T.tag==='bound'||T.tag==='apply')return this.originalValue(T,env,ctx);
    if(T.tag==='scalar'&&T.T.$==='Enu'&&T.T.ks.join(',')==='Q0,Q1,Q2')return B.Qnt();
    if(T.tag==='universe')return B.Typ(typeof T.quantity==='number'?B.Qua([B.None(),B.Lone(),B.Many()][T.quantity]):this.originalValue(T.quantity,env,ctx));
    if(T.tag==='identity')return B.Eql(this.originalValue(T.a,env,ctx),this.originalValue(T.b,env,ctx),this.originalType(T.A,env,ctx));
    if(T.tag==='arrow'){
      const level=this.depth++,q=[B.None(),B.Lone(),B.Many()][T.q],A=this.originalType(T.A,env,ctx);
      return B.All(q,T.key,level,A,x=>{const c=new Map(ctx),e=new Map(env);c.set(level,T.key);e.set(T.key,{sourceTerm:x,sourceContext:c});return this.originalType(T.B,e,c);});
    }
    throw Error('Original typed reconstruction is not implemented for '+T.tag);
  }
  originalValue(x,env,ctx){
    const B=this.B;
    if(x.tag==='bound'){
      for(const[level,key]of ctx)if(key===x.key)return typeof level==='number'?B.Var('_',level):B.Ref(level.slice(4));
      const value=env.get(x.key);
      if(value?.sourceTerm!==undefined)return this.rebase(value.sourceTerm,value.sourceContext??ctx,ctx);
      if(value?.expression&&value.expression.key!==x.key)return this.originalValue(value.expression,env,ctx);
      throw Error('A typed source construction is unavailable for '+x.key);
    }
    if(x.tag==='family'||x.tag==='universe'||x.tag==='arrow'||x.tag==='identity')return this.originalType(x,env,ctx);
    if(x.tag==='type')return this.originalType(x.T,env,ctx);
    if(x.tag==='apply')return B.App(this.originalValue(x.f,env,ctx),this.originalValue(x.x,env,ctx));
    if(x.tag==='erased-reference'||x.tag==='physical-reference')return B.Ref(x.key);
    if(x.tag==='nat-literal')return B.Lit('Nat',x.n);
    if(x.tag==='quantity-minimum')return B.Min(this.originalValue(x.a,env,ctx),this.originalValue(x.b,env,ctx));
    if(x.tag==='constant'&&x.value.$==='Lab'&&/^Q[012]$/.test(x.value.k))return B.Qua([B.None(),B.Lone(),B.Many()][Number(x.value.k[1])]);
    if(x.tag==='source')return this.rebase(x.term,x.context,ctx);
    if(x.sourceTerm!==undefined)return x.sourceTerm;
    throw Error('A typed original source value is unavailable for '+x.tag);
  }
  rebase(term,from,to){
    const levels=new Map([...to].map(([level,key])=>[key,level]));
    const visit=x=>{
      if(!x||typeof x!=='object')return x;
      if(x.$==='Var'&&from.has(x.i)&&typeof levels.get(from.get(x.i))==='number')return {...x,i:levels.get(from.get(x.i))};
      if(Array.isArray(x))return x.map(visit);
      return Object.fromEntries(Object.entries(x).map(([k,v])=>[k,k==='s'?v:visit(v)]));
    };
    return this.B.term_higher(visit(this.B.term_lower(term)));
  }
  descriptor(key) {
    const prior=this.families.get(key);if(prior!==undefined)return prior;
    const d=this.book.tlds[key];if(d?.$!=='ADT')throw Error('Not a checked datatype: '+key);
    const result={key,kernel:this.name(key),parameters:[],constructors:[],quantity:1};
    this.families.set(key,result);
    let T=d.T,ctx=new Map();const xs=[];
    for(let i=0;i<d.n;i++) {
      const F=this.B.term_wnf(this.book,T);if(F.$!=='All')throw Error('Missing family parameter');
      const k=key+'.parameter.'+i,x=this.open(F,ctx,k);
      result.parameters.push({key:k,q:this.q(F.q),type:this.type(F.A,ctx)});xs.push(x.v);ctx=x.ctx;T=F.B(x.v);
    }
    const G=this.B.term_wnf(this.book,T);
    if(G.$!=='Typ')throw Error('A checked family must return its kind');
    result.quantity=G.g.$==='Qua'?this.q(G.g.q):this.value(G.g,this.B.Qnt(),ctx);
    for(const c of d.c) {
      let T=this.B.tele_fill(this.book,c.T,xs,this.B.ctx_nil()),env=new Map(ctx);
      const ctor={key:c.k,kernel:this.name(c.k),fields:[]};result.constructors.push(ctor);
      for(let j=0;j<c.n;j++) {
        const F=this.B.term_wnf(this.book,T);if(F.$!=='All')throw Error('Missing constructor field');
        const k=c.k+'.field.'+j,x=this.open(F,env,k);
        ctor.fields.push({key:k,q:this.q(F.q),type:this.type(F.A,env)});env=x.ctx;T=F.B(x.v);
      }
    }
    return result;
  }
}
