"""Fingerprint the actual selected runtime closure, without changing its policy.

A manifest is a frozen inventory to validate again before use. It is not a proof
that every function exported by an installed Linux library is unreachable.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT=Path(__file__).resolve().parents[2]


def environment_snapshot():
    influential={k for k in os.environ if k.startswith(('MIMALLOC_','MALLOC_','LEAN_','PYTHON','NODE_','UV_',
                    'LLVM_','CLANG_','CCC_','LD_','GLIBC_','OPENSSL_','ASAN_','MSAN_','TSAN_','LSAN_','UBSAN_','LC_'))}
    influential.update(('PATH','LD_PRELOAD','LD_AUDIT','LD_LIBRARY_PATH','NODE_OPTIONS','NODE_PATH',
                        'UV_USE_IO_URING','PYTHONPATH','PYTHONHOME','PYTHONSTARTUP','TMPDIR','GLIBC_TUNABLES',
                        'LANG','LC_ALL','LC_CTYPE'))
    influential.update(('CC','CXX','CFLAGS','CXXFLAGS','CPPFLAGS','LDFLAGS','CPATH','C_INCLUDE_PATH',
                        'CPLUS_INCLUDE_PATH','COMPILER_PATH','LIBRARY_PATH'))
    return {k:hashlib.sha256(os.environ[k].encode()).hexdigest() for k in sorted(influential) if k in os.environ}


def digest(path):
    h=hashlib.sha256()
    with Path(path).open('rb') as f:
        for block in iter(lambda:f.read(1024*1024),b''):
            h.update(block)
    return h.hexdigest()


def kernel_identity():
    notes=Path('/sys/kernel/notes')
    return {'release':os.uname().release,'version':os.uname().version,
            'notes_sha256':digest(notes) if os.access(notes,os.R_OK) else None}


def execute(command):
    return subprocess.check_output(list(map(str,command)),cwd=ROOT,text=True,timeout=20)


def dynamic_dependencies(path):
    r=subprocess.run(['ldd',str(path)],capture_output=True,text=True,timeout=20)
    if r.returncode and 'not a dynamic executable' not in r.stderr+r.stdout:
        raise RuntimeError(f'Cannot inventory dependencies of {path}: {r.stderr}')
    return {Path(s).resolve() for s in re.findall(r'(?:=>\s*)?(/[^\s()]+)',r.stdout) if Path(s).is_file()}


def inventory(root=ROOT):
    root=Path(root).resolve()
    frontend=json.loads((root/'tools/admission/frontend.lock.json').read_text())
    verifier=json.loads((root/'tools/verifier/verifier.lock.json').read_text())
    node=Path(shutil.which('node')).resolve()
    versions=json.loads(execute([node,'-p','JSON.stringify(process.versions)']))
    if 'v'+versions['node']!=frontend['node']:
        raise RuntimeError('Selected Node differs from the installed frontend pin')
    selected={Path(sys.executable).resolve(),node,Path('/usr/bin/clang-19').resolve(),Path('/usr/bin/ld').resolve(),
              root/f'.tools/build/verifier-{verifier["sourceSha256"]}/bendtt-budget',
              root/'tools/admission/installed/stack.node',
              root/'tests/accounting/.build/jayacct-trace',root/'tests/accounting/.build/libjayacct.so'}
    kernel=next(p for p in selected if p.name=='bendtt-budget')
    if digest(kernel)!=verifier['kernelSha256']:
        raise RuntimeError('Selected BendTT differs from its immutable binary pin')
    for name,expected in frontend['files'].items():
        path=root/'tools/admission/installed'/name
        if digest(path)!=expected:raise RuntimeError(f'Frontend installation pin changed: {name}')
        if path.suffix=='.node':selected.add(path)
    # Import the fixed host entry modules in a separate interpreter. List ELF
    # extension modules and all source modules that this real entry closure loads.
    code=('import tools.service.controller,tools.service.staging,tools.service.abi; '
          'import tools.accounting.client; import sys,json; '
          'print(json.dumps(sorted({m.__file__ for m in sys.modules.values() '
          'if getattr(m,"__file__",None) and not m.__file__.startswith("<")})))')
    host_modules={Path(p).resolve() for p in json.loads(execute([sys.executable,'-B','-c',code]))}
    selected.update(p for p in host_modules if p.suffix=='.so')
    dependencies=set()
    for p in sorted(selected):dependencies.update(dynamic_dependencies(p))
    source_paths=set(host_modules)
    accounting_build=root/'tests/accounting/.build/BUILD.json'
    built=json.loads(accounting_build.read_text())
    source_paths.add(accounting_build)
    for path,expected in built['link_inputs'].items():
        if digest(path)!=expected:raise RuntimeError(f'Observer link input changed: {path}')
        source_paths.add(Path(path))
    for directory in ('native','tools/native','tools/service','tools/admission','tools/verifier','tools/accounting'):
        for path in (root/directory).rglob('*'):
            if path.is_file() and path.suffix in ('.c','.h','.cc','.cpp','.hpp','.S','.s','.py','.mjs','.cjs','.json','.bend') and '__pycache__' not in path.parts:
                source_paths.add(path.resolve())
    # Reports generated by this inventory are not part of their own hash graph.
    source_paths={p for p in source_paths if not (p.parent==root/'tools/accounting' and p.name in ('CLOSURE.json','CLOSURE_SOURCES.json'))}
    files={str(p):digest(p) for p in sorted(selected|dependencies|source_paths) if p.is_file()}
    environment=environment_snapshot()
    # A concurrent root edit must not silently produce a mixed artifact manifest.
    for p,expected in files.items():
        if digest(p)!=expected:raise RuntimeError(f'Closure changed during inventory: {p}')
    return {'format':'jaydb-accounting-closure-v1','scope':'selected fixed userspace entry closure',
            'complete_measurement':False,'root':str(root),'node_versions':versions,
            'python_version':sys.version,'kernel':os.uname().release,'kernel_identity':kernel_identity(),
            'page_size':os.sysconf('SC_PAGESIZE'),
            'selected_elf':[str(p) for p in sorted(selected)],'dependencies':[str(p) for p in sorted(dependencies)],
            'files':files,'environment_hashes':environment,
            'revalidation_required':'Every file and influential environment hash must still match; changed artifacts need a new inventory.'}


def validate(manifest):
    for path,expected in manifest['files'].items():
        if digest(path)!=expected:raise RuntimeError(f'Frozen closure changed: {path}')
    if environment_snapshot()!=manifest['environment_hashes']:
        raise RuntimeError('Frozen environment changed')
    if os.uname().release!=manifest['kernel'] or os.sysconf('SC_PAGESIZE')!=manifest['page_size']:
        raise RuntimeError('Frozen kernel/page domain changed')
    if kernel_identity()!=manifest['kernel_identity']:
        raise RuntimeError('Frozen kernel build identity changed')


if __name__=='__main__':
    parser=argparse.ArgumentParser()
    parser.add_argument('--output',type=Path,default=ROOT/'tools/accounting/CLOSURE.json')
    parser.add_argument('--validate',type=Path)
    args=parser.parse_args()
    if args.validate:
        validate(json.loads(args.validate.read_text()))
        print('Frozen accounting closure matches')
    else:
        manifest=inventory()
        args.output.write_text(json.dumps(manifest,indent=2)+'\n')
        print(f'Inventoried {len(manifest["files"])} files and {len(manifest["selected_elf"])} selected ELF artifacts')
